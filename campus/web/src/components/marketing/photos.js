/** Sized, auto-format (WebP/AVIF), cropped Unsplash URL. */
export function photoSrc(photo, width = 1200, { height, quality = 75 } = {}) {
  if (!photo) return "";
  const params = new URLSearchParams({ w: String(width), q: String(quality), auto: "format", fit: "crop" });
  if (height) params.set("h", String(height));
  return `${photo.src}&${params.toString()}`;
}

/** srcSet for responsive images. */
export function photoSrcSet(photo, widths = [480, 800, 1200, 1600], opts) {
  return widths.map((w) => `${photoSrc(photo, w, opts)} ${w}w`).join(", ");
}
